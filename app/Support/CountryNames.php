    ];

    /**
     * Code => name in the language given, sorted as that language sorts.
     *
     * @return array<string, string>
     */
    public static function options(?string $locale = null): array
    {
        $locale ??= app()->getLocale();
        $names = [];

        foreach (self::CODES as $code) {
            $names[$code] = self::name($code, $locale);
        }

        (new Collator($locale))->asort($names);

        return $names;
    }

    /** A code's name in the language given; the code itself where there is none. */
    public static function name(string $code, ?string $locale = null): string
    {
        $name = Locale::getDisplayRegion('-'.$code, $locale ?? app()->getLocale());

        return $name !== '' && $name !== $code ? $name : $code;
    }
}
