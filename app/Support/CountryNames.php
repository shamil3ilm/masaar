 * language - for the dropdown that used to be a two-letter text box.
 *
 * The codes are ISO 3166-1 alpha-2's officially assigned 249, the list both
 * invoice formats take a country from (UBL 2.1 cbc:IdentificationCode with
 * listID ISO3166-1:Alpha2; EN 16931 BT-55, BT-80). The names are the
 * Unicode CLDR's, through the intl extension, so Arabic names are written
 * by the people who maintain them rather than here.
 */
final class CountryNames
{
    public const CODES = [
        'AD', 'AE', 'AF', 'AG', 'AI', 'AL', 'AM', 'AO', 'AQ', 'AR', 'AS', 'AT', 'AU', 'AW', 'AX', 'AZ', 'BA', 'BB', 'BD', 'BE',
        'BF', 'BG', 'BH', 'BI', 'BJ', 'BL', 'BM', 'BN', 'BO', 'BQ', 'BR', 'BS', 'BT', 'BV', 'BW', 'BY', 'BZ', 'CA', 'CC', 'CD',
