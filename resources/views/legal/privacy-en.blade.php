<p>{{ $who }} operates this e-invoicing service. This notice explains what personal data we handle, why, and the rights you have under the Personal Data Protection Law (PDPL) of the Kingdom of Saudi Arabia.</p>

<h2>Two roles</h2>
<p>For your account - your name, email address and how you use the service - we decide how the data is used, so we are its controller. For the invoices your company issues through the service, including any personal data about your buyers, your company decides; we process that data on its behalf and only to provide the service.</p>

<h2>What we collect</h2>
<ul>
    <li>Account details: name, email address, password (stored only as a one-way hash), language and two-factor settings.</li>
    <li>Company details: legal name, VAT number, commercial registration and national address.</li>
    <li>Invoices and the details on them, the documents filed with ZATCA and ZATCA's responses.</li>
    <li>Security records: sign-ins, failed attempts, IP addresses and an audit trail of changes.</li>
    <li>Support tickets and the files attached to them, and records of payments for your plan.</li>
</ul>

<h2>Why we use it</h2>
<ul>
    <li>To provide the service: issuing, signing, clearing, reporting and storing invoices.</li>
    <li>To meet legal duties, including keeping tax records for as long as the law requires.</li>
    <li>To keep accounts and invoices secure and to investigate misuse.</li>
    <li>To answer support requests and to bill for your plan.</li>
</ul>

<h2>Who receives it</h2>
<p>ZATCA receives the invoices filed through the service, as the law requires. We use providers for hosting and for sending email, bound to protect the data and to use it only for us. We do not sell personal data or use it for advertising.</p>

<h2>How long we keep it</h2>
<p>Invoices and the records about them are kept for at least the period Saudi tax law requires a taxpayer to keep them. Account data is kept while the account is open. When you delete your account, your name, email address and sign-in are erased; records the law requires us or your company to keep remain, no longer linked to you by name.</p>

<h2>Your rights</h2>
<p>You may ask to be told about, to see, to correct and to have destroyed the personal data we hold about you, and to withdraw consent where we rely on it. You can change your details and delete your account yourself under My account. For anything else, write to us at the address below. If you are a buyer named on an invoice, contact the company that issued it.</p>

<h2>Security</h2>
<p>Data is encrypted in transit, passwords are hashed, signing keys are protected, and access is limited by role and to those who need it. Two-factor authentication is available to everyone and required for platform staff.</p>

<h2>Changes</h2>
<p>We will publish any change to this notice here, with a new version, and tell account holders of significant changes by email.</p>
