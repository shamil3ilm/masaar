<?php

declare(strict_types=1);

namespace Tests\Feature\Compliance\SaudiArabia;

use App\Domains\Compliance\Countries\SaudiArabia\Exceptions\FatooraException;
use App\Domains\Compliance\Countries\SaudiArabia\Filing\Submitter;
use App\Domains\Compliance\Countries\SaudiArabia\Models\ChainEntry;
use App\Domains\Compliance\Countries\SaudiArabia\Signing\CredentialStore;
use App\Domains\Invoice\Models\Invoice;
use App\Domains\Invoice\Services\InvoiceNumbering;
use App\Domains\Organization\Models\Branch;
use App\Domains\Organization\Models\EgsUnit;
use App\Domains\Organization\Models\Organization;
use App\Domains\Organization\Services\Tills;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Storage;
use Tests\Fixtures\SigningCredentials;
use Tests\TestCase;

/**
 * Several tills in one branch, each its own EGS unit: its own counter,
 * chain, credentials and numbering series.
 *
 * "The E-Invoice Solution unit must not generate more than one sequence so
 * that all invoices generated by an E-Invoice Solution Unit are linked using
 * 'Previous Invoice Hash' value into a single chain" (ZATCA E-Invoicing
 * Detailed Guidelines p28, p35) - one sequence per unit, and every unit a
 * taxpayer issues from registered on its own (p39; FAQ p59). Two tills
 * interleaving their sales must each keep an unbroken chain of their own.
 */
class TillChainTest extends TestCase
{
    use RefreshDatabase;
    use SigningCredentials;

    private Organization $acme;

    private Branch $riyadh;

    private EgsUnit $second;

    /** @var array<string, array{privateKey: string, certificate: string}> */
    private array $keys = [];

    protected function setUp(): void
    {
        parent::setUp();

        Storage::fake('creds');
        config(['fatoora.signing.disk' => 'creds']);

        $this->acme = Organization::create([
            'name' => 'Acme Grocery',
            'country' => 'SA',
            'vat_number' => '300000000000003',
            'street' => 'King Fahd Road',
            'building_number' => '1234',
            'district' => 'Al Olaya',
            'city' => 'Riyadh',
            'postal_code' => '12345',
            'compliance_profile' => ['zatca_onboarded' => true],
        ]);

        $this->riyadh = Branch::withoutTenantScope(fn () => Branch::create([
            'org_id' => $this->acme->id,
            'name' => 'Olaya Store',
            'device_serial' => 'EGS-OLAYA',
            'street' => 'King Fahd Road',
            'building_number' => '1234',
            'district' => 'Al Olaya',
            'city' => 'Riyadh',
            'postal_code' => '12345',
            'onboarding_status' => 'active',
        ]));

        $this->second = app(Tills::class)->add($this->riyadh);
        $this->second->forceFill(['onboarding_status' => 'active'])->save();

        $this->onboard(null);
        $this->onboard($this->riyadh->id);
        $this->onboard($this->second->id);
    }

    public function test_two_tills_interleave_their_own_chains(): void
    {
        $first = [];
        $second = [];

        foreach (range(1, 3) as $round) {
            $first[] = $this->issue($this->draft($this->riyadh->id));
            $second[] = $this->issue($this->draft($this->second->id));
        }

        $this->assertSame([1, 2, 3], array_map(fn (Invoice $invoice): int => $invoice->icv, $first));
        $this->assertSame([1, 2, 3], array_map(fn (Invoice $invoice): int => $invoice->icv, $second));

        foreach ([$first, $second] as $chain) {
            $this->assertNull($chain[0]->previous_invoice_hash);
            $this->assertSame($chain[0]->hash, $chain[1]->previous_invoice_hash);
            $this->assertSame($chain[1]->hash, $chain[2]->previous_invoice_hash);
        }

        $this->assertSame($this->riyadh->id, $first[2]->device_id);
        $this->assertSame($this->second->id, $second[2]->device_id);

        // Each signed with its own certificate, and each chain entry names it.
        $this->assertSame($this->body($this->keys[$this->riyadh->id]['certificate']), $this->signer($first[0]));
        $this->assertSame($this->body($this->keys[$this->second->id]['certificate']), $this->signer($second[0]));
        $this->assertSame(3, ChainEntry::withoutTenantScope(fn () => ChainEntry::query()->where('device_id', $this->second->id)->count()));

        // And numbered from a series of its own.
        $year = app(InvoiceNumbering::class)->now($this->acme->id)->format('Y');
        $this->assertSame('INV-T01-'.$year.'-00003', $first[2]->invoice_number);
        $this->assertSame('INV-T02-'.$year.'-00003', $second[2]->invoice_number);
    }

    public function test_branch_issues_on_its_first_till(): void
    {
        $invoice = $this->issue($this->draft(null, $this->riyadh->id));

        $this->assertSame($this->riyadh->id, $invoice->device_id);
        $this->assertSame(1, $invoice->icv);
    }

    public function test_retired_till_never_issues_again(): void
    {
        $this->second->forceFill(['status' => EgsUnit::RETIRED])->save();
        $draft = $this->draft($this->second->id);

        try {
            $this->issue($draft);
            $this->fail('A retired till issued a document.');
        } catch (FatooraException $e) {
            $this->assertSame(EgsUnit::RETIRED, $e->getContext()['status']);
        }

        $this->assertNull(Invoice::withoutTenantScope(fn () => $draft->fresh())->icv);
    }

    public function test_default_skips_a_retired_first_till(): void
    {
        EgsUnit::withoutTenantScope(fn () => EgsUnit::query()->whereKey($this->riyadh->id)->update(['status' => EgsUnit::RETIRED]));

        $invoice = $this->issue($this->draft(null, $this->riyadh->id));

        $this->assertSame($this->second->id, $invoice->device_id);
    }

    public function test_named_till_without_certificate_refused(): void
    {
        app(CredentialStore::class)->forget($this->acme->id, $this->second->id);

        $this->expectException(FatooraException::class);

        $this->issue($this->draft($this->second->id));
    }

    public function test_filed_with_its_own_tills_credentials(): void
    {
        $invoice = $this->issue($this->draft($this->second->id));

        $device = app(CredentialStore::class)->forInvoice($this->acme->id, $invoice->device_id, $invoice->branch_id, $invoice->id, $invoice->signed_xml);

        $this->assertSame('secret-'.$this->second->id, $device->secret);
    }

    private function onboard(?string $unitId): void
    {
        $keys = $this->selfSignedCredentials();
        $this->keys[$unitId ?? $this->acme->id] = $keys;

        app(CredentialStore::class)->put($this->acme->id, $unitId, CredentialStore::PCSID, [
            'privateKey' => $keys['privateKey'],
            'pcsid' => $keys['certificate'],
            'secret' => 'secret-'.($unitId ?? $this->acme->id),
        ]);
    }

    /**
     * A draft, on a till when one is named, else for a branch.
     */
    private function draft(?string $tillId, ?string $branchId = null): Invoice
    {
        $invoice = Invoice::withoutTenantScope(fn () => Invoice::create([
            'org_id' => $this->acme->id,
            'branch_id' => $branchId ?? $this->riyadh->id,
            'type' => 'simplified',
            'document_type' => 'invoice',
            'status' => 'draft',
            'issue_date' => now()->toDateString(),
            'supply_date' => now()->toDateString(),
            'currency' => 'SAR',
            'subtotal' => '100.00',
            'tax_amount' => '15.00',
            'total' => '115.00',
        ]));

        if ($tillId !== null) {
            $invoice->forceFill(['device_id' => $tillId])->save();
        }

        $invoice->lines()->create([
            'description' => 'Bread',
            'quantity' => '1.000',
            'unit_price' => '100.00',
            'tax_rate' => '15.00',
            'tax_amount' => '15.00',
            'line_total' => '115.00',
        ]);

        return $invoice;
    }

    private function issue(Invoice $invoice): Invoice
    {
        app(Submitter::class)->generate($invoice->fresh(['lines']), $this->acme->fresh());

        return Invoice::withoutTenantScope(fn () => $invoice->fresh());
    }

    private function signer(Invoice $invoice): ?string
    {
        preg_match('/<ds:X509Certificate>([^<]+)<\/ds:X509Certificate>/', (string) $invoice->signed_xml, $match);

        return isset($match[1]) ? preg_replace('/\s+/', '', $match[1]) : null;
    }

    private function body(string $pem): string
    {
        return (string) preg_replace('/-----[A-Z ]+-----|\s+/', '', $pem);
    }
}
