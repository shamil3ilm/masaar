<?php

declare(strict_types=1);

namespace Tests\Feature\Compliance\SaudiArabia;

use App\Domains\Compliance\Countries\SaudiArabia\Filing\Submitter;
use App\Domains\Compliance\Countries\SaudiArabia\Rules\FatooraConfig;
use App\Domains\Compliance\Countries\SaudiArabia\Signing\CredentialStore;
use App\Domains\Invoice\Models\Invoice;
use App\Domains\Organization\Models\Branch;
use App\Domains\Organization\Models\EgsUnit;
use App\Domains\Organization\Models\Organization;
use App\Domains\Organization\Services\Tills;
use DOMDocument;
use DOMXPath;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Storage;
use Tests\Fixtures\SigningCredentials;
use Tests\Fixtures\ZatcaSdk;
use Tests\TestCase;

/**
 * Two tills of one branch selling at the same time, judged by ZATCA's own
 * validator.
 *
 * A taxpayer may run several E-Invoice Solution Units, each registered and
 * holding its own cryptographic stamp identifier (E-Invoicing Detailed
 * Guidelines p9 2.7, p10 2.10, p39; FAQ p59), and "the E-Invoice Solution
 * unit must not generate more than one sequence so that all invoices
 * generated by an E-Invoice Solution Unit are linked using 'Previous
 * Invoice Hash' value into a single chain" (p28, p35). So two tills whose
 * sales interleave each keep a counter (KSA-16) running 1, 2, 3 and a PIH
 * (KSA-13) naming that till's own previous document - the first naming the
 * SDK's default hash - and each document passes ZATCA's content checks.
 *
 * The SDK's PIH stage compares against a file of its own, so the chains are
 * read from the documents here; its content stages judge each document.
 * Set ZATCA_SDK_PATH to run these; they skip without it.
 */
class TillConformanceTest extends TestCase
{
    use RefreshDatabase;
    use SigningCredentials;
    use ZatcaSdk;

    private Organization $organization;

    private Branch $branch;

    private EgsUnit $second;

    protected function setUp(): void
    {
        parent::setUp();

        Storage::fake('creds');
        config(['fatoora.signing.disk' => 'creds']);

        $this->organization = Organization::create([
            'name' => 'Acme Trading',
            'country' => 'SA',
            'vat_number' => '399999999900003',
            'street' => 'King Fahd Road',
            'building_number' => '1234',
            'district' => 'Al Olaya',
            'city' => 'Riyadh',
            'postal_code' => '12345',
            'cr_number' => '1010101010',
            'compliance_profile' => ['zatca_onboarded' => true],
        ]);

        $this->branch = Branch::withoutTenantScope(fn () => Branch::create([
            'org_id' => $this->organization->id,
            'name' => 'Olaya Store',
            'device_serial' => 'EGS-OLAYA',
            'street' => 'King Fahd Road',
            'building_number' => '1234',
            'district' => 'Al Olaya',
            'city' => 'Riyadh',
            'postal_code' => '12345',
            'onboarding_status' => 'active',
        ]));
        $this->second = app(Tills::class)->add($this->branch, 'Express lane');

        // The first till holds ZATCA's own test certificate where the SDK
        // ships one; the second a certificate of its own.
        $first = $this->authorityCredentials($this->sdk()->path()) ?? $this->selfSignedCredentials(serial: 1);
        $second = $this->selfSignedCredentials(serial: 2);

        foreach ([[$this->branch->id, $first], [$this->second->id, $second]] as [$unit, $keys]) {
            app(CredentialStore::class)->put($this->organization->id, $unit, CredentialStore::PCSID, [
                'privateKey' => $keys['privateKey'], 'pcsid' => $keys['certificate'], 'secret' => 'secret',
            ]);
        }
    }

    public function test_interleaved_tills_keep_their_own_chains(): void
    {
        $this->requireSdk();

        $chains = [$this->branch->id => [], $this->second->id => []];

        foreach (range(1, 3) as $round) {
            foreach (array_keys($chains) as $index => $till) {
                $chains[$till][] = $this->signed($till, 'TILL-'.($index + 1).'-'.$round);
            }
        }

        foreach ($chains as $till => $documents) {
            $previous = FatooraConfig::GENESIS_PIH;

            foreach ($documents as $index => $document) {
                $this->assertSame((string) ($index + 1), $this->reference($document['xml'], 'ICV'), 'a till did not count from 1 on its own');
                $this->assertSame($previous, $this->reference($document['xml'], 'PIH'), 'a till named another till\'s document as its predecessor');
                $previous = $document['hash'];

                $result = $this->validate($document['xml']);
                $this->assertTrue(
                    $this->sdk()->contentPassed($result),
                    "ZATCA rejected till {$till}'s document {$document['number']}:\n".implode("\n", $result['errors'])
                );
                $this->assertSame([], array_values(array_filter($result['errors'], static fn (string $e): bool => str_starts_with($e, 'BR-'))));
            }
        }
    }

    /**
     * A credit note on one till takes that till's next counter and names its
     * previous document, whatever the other till issued in between.
     */
    public function test_a_note_continues_its_tills_chain(): void
    {
        $this->requireSdk();

        $sale = $this->signed($this->second->id, 'LANE-1');
        $this->signed($this->branch->id, 'MAIN-1');
        $note = $this->signed($this->second->id, 'LANE-CN-1', 'credit_note');

        $this->assertSame('2', $this->reference($note['xml'], 'ICV'));
        $this->assertSame($sale['hash'], $this->reference($note['xml'], 'PIH'));

        $result = $this->validate($note['xml']);
        $this->assertTrue($this->sdk()->contentPassed($result), implode("\n", $result['errors']));
    }

    /**
     * An additional document reference's value: the counter's UUID, or the
     * previous invoice hash's embedded object.
     */
    private function reference(string $xml, string $id): string
    {
        $dom = new DOMDocument;
        $dom->loadXML($xml);
        $xpath = new DOMXPath($dom);
        $xpath->registerNamespace('cac', 'urn:oasis:names:specification:ubl:schema:xsd:CommonAggregateComponents-2');
        $xpath->registerNamespace('cbc', 'urn:oasis:names:specification:ubl:schema:xsd:CommonBasicComponents-2');

        $nodes = $xpath->query($id === 'ICV'
            ? "//cac:AdditionalDocumentReference[cbc:ID='ICV']/cbc:UUID"
            : "//cac:AdditionalDocumentReference[cbc:ID='PIH']/cac:Attachment/cbc:EmbeddedDocumentBinaryObject");

        $this->assertSame(1, $nodes === false ? 0 : $nodes->length, "the document carries no {$id}");

        return trim((string) $nodes->item(0)?->textContent);
    }

    /**
     * @return array{xml: string, hash: string, number: string}
     */
    private function signed(string $till, string $number, string $document = 'invoice'): array
    {
        $isNote = $document !== 'invoice';

        $invoice = Invoice::withoutTenantScope(fn () => Invoice::create([
            'org_id' => $this->organization->id,
            'branch_id' => $this->branch->id,
            'invoice_number' => $number,
            'type' => 'simplified',
            'document_type' => $document,
            'billing_ref' => $isNote ? 'LANE-1' : null,
            'adjustment_reason' => $isNote ? 'Returned goods' : null,
            'status' => 'draft',
            'issue_date' => now()->toDateString(),
            'supply_date' => now()->toDateString(),
            'currency' => 'SAR',
            'subtotal' => '100.00',
            'tax_amount' => '15.00',
            'total' => '115.00',
        ]));
        $invoice->forceFill(['device_id' => $till])->save();

        $invoice->lines()->create([
            'description' => 'Bread',
            'description_ar' => 'خبز',
            'quantity' => '1.000',
            'unit_price' => '100.00',
            'tax_rate' => '15.00',
            'tax_category' => 'S',
            'tax_amount' => '15.00',
            'line_total' => '115.00',
        ]);

        $result = app(Submitter::class)->generate($invoice->fresh(['lines']), $this->organization);

        $this->assertNotEmpty($result['signed_xml'], 'the invoice was not signed');

        return ['xml' => $result['signed_xml'], 'hash' => $result['hash'], 'number' => $number];
    }
}
